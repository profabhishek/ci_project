			<h3><strong> A Brief on the city: Ahmedabad</strong></h3>
			
								<p><strong>Ahmedabad</strong> also known as Amdavad in Gujarati is the largest city and former capital of Gujarat state in India. It is the administrative headquarters of the Ahmedabad district and the seat of the Gujarat High Court. Ahmedabad is located on the banks of the Sabarmati River, 30 km (19 mi) from the state capital Gandhinagar, which is its twin city. Ahmedabad has been selected as one of the hundred Indian cities to be developed as a smart city under PM Narendra Modi's flagship Smart Cities.</p>
								
			<h4><strong>Education:</strong></h4>
			<p>A large number of colleges in the city are affiliated with Gujarat University; Gujarat Technological University. Other educational institutions in Ahmedabad include the Indian Institute of Management Ahmedabad, the Gujarat National Law University, the National Institute of Design, the Pandit Deendayal Petroleum University, and the Gujarat National Law University, Entrepreneurship Development Institute of India.</p>
				
			
			<h4><strong>Culture and Tourism:</strong></h4>
							<p>Ahmedabad observes a wide range of festivals. Popular celebrations and observances include Uttarayan, an annual kite-flying day on 14 and 15 January. Nine nights of Navratri are celebrated with people performing Garba, the most popular folk dance of Gujarat, at venues across the city. The festival of lights, Deepavali, is celebrated with the lighting of lamps in every house, decorating the floors with rangoli, and the lighting of firecrackers. The annual Rath Yatra procession on the Ashadh-sud-bij date of the Hindu calendar at the Jagannath Temple and the procession of Tajia during the Muslim holy month of Muharram are important events. One of the most popular forms of meal in Ahmedabad is a typical Gujarati thali which was first served commercially by Chandvilas Hotel in 1900. It consists of roti (Chapati), dal, rice and shaak (cooked vegetables, sometimes with curry), with accompaniments of pickles and roasted papads. Beverages include buttermilk and tea; sweet dishes include laddoo, mango, and vedhmi. Dhoklas, theplas and dhebras are also very popular dishes in Ahmedabad. Parts of Ahmedabad are known for their folk art. The artisans of Rangeela pol make tie-dyed bandhinis, while the cobbler shops of Madhupura sell traditional mojdi (also known as mojri) footwear. Idols of Ganesha and other religious icons are made in huge numbers in the Gulbai Tekra area. The shops at the Law Garden sell mirror work handicraft.<a href="https://incredibleindia.org/"target="_blank">Read More</a></p>

