			<h3><strong> A Brief on the city:</strong></h3>
			
								<p><strong>Hyderabad</strong> is the capital of the southern Indian state of Telangana  situated along the banks of the Musi River. Much of Hyderabad is situated on a hilly terrain around artificial lakes, including Hussain Sagar—predating the city's founding.

The city of smiles, of lights, of a thousand faces, endearingly called the Pearl City, Hyderabad offers a variety of tourist attractions ranging from Heritage monuments, Lakes and Parks, Gardens and Resorts, Museums to delectable cuisine and a delightful shopping experience. To the traveler, Hyderabad offers a fascinating panorama of the past, fused with an crunched cultural and historical tradition spanning 400 colorful years.</p>
								
			<h4><strong>Education:</strong></h4>
			<p>Many of professional colleges in Hyderabad, are affiliated with Jawaharlal Nehru Technological University Hyderabad (JNTUH) Osmania University (OU).

There are state and Central universities in Hyderabad. The Central Universities are the University of Hyderabad, Maulana Azad National Urdu University and the English and Foreign Languages University. Osmania University, Dr. B. R. Ambedkar Open University, established in 1982, is the first distance-learning Open University in India. 

Hyderabad is also home to a number of centres specializing in particular fields such as biomedical sciences, biotechnology and pharmaceuticals, such as the National Institute of Pharmaceutical Education and Research (NIPER) and National Institute of Nutrition (NIN). 
Institutes in Hyderabad include the National Institute of Rural Development, Indian School of Business, Institute of Public Enterprise, Administrative Staff College of India and Sardar Vallabhbhai Patel National Police Academy. Technical and Engineering schools include International Institute of Information Technology, Hyderabad (IIITH), Birla Institute of Technology and Science, Pilani– Hyderabad(BITS Hyderabad) and Indian Institute of Technology, Hyderabad (lIT-H) as well as Agricultural Engineering Institutes such as the International Crops Research Institute for the Semi- Arid Tropics (lCRISAT) and the Acharya N. G. Ranga Agricultural University. </p>
				
			
