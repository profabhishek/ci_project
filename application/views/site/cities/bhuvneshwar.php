			<h3><strong> A Brief on the city:</strong></h3>
			
							<p><strong>Bhubaneswar</strong> is the capital of the Indian state of Odisha. It is the largest city in Odisha and is a centre of economic and religious importance in Eastern India.</p>
								
			<h4><strong>Education:</strong></h4>
			<p>Utkal University, has many degree colleges, law colleges, Medical and Pharmaceutical college under its jurisdictional affiliation. Orissa University of Agriculture and Technology established in 1962, is the second oldest agricultural university in the country. Utkal University of Culture is dedicated to research, teaching and education.

Bhubaneswar has a large number of institutes for higher education. Bhubaneswar is one of the few cities in India which houses IIT, NISER, and many other premier Government institutes. Premier educational institutions include the IIT Bhubaneswar, National Institute of Science Education and Research, International Institute of Information Technology, Bhubaneswar (IIIT-Bh), Xavier Institute of Management (XIMB), Institute of Mathematics and Applications (IOMA), National Institute of Fashion Technology, Institute of Physics, Institute of Life Sciences, Institute of Minerals and Materials Technology, Central Institute of Freshwater Aquaculture, Regional Medical Research Center and Regional Institute of Education.  The premiere Engineering college owned by the state Government of Odisha, College of Engineering and Technology, Bhubaneswar, is the most comprehensive engineering Institute in the capital having a set of specialization which include, electrical engineering, architecture, textile, and fashion technology, etc. The Central Institute of Plastics Engineering and Technology located in Bhubaneswar is a unique Institute owned by Government of India. Rama Devi Women's University is a University located in Bhubaneswar which is specifically dedicated for imparting education to women.</p>
			
			<h4><strong>Culture and Tourism:</strong></h4>
			<p>Bhubaneswar is supposed to have had over one thousand temples, earning the tag of the 'Temple City of India'. Temples are made in the Kalinga architectural style with a pine spire that curves up to a point over the sanctum housing the presiding deity and a pyramid-covered hall where people sit and pray.

Along with the old town, the region of Bhubaneswar, historically was often depicted as EkamraKshetra. With the diverse ranges of heritage resources, it showcases significant sacred cultural landscape components which have evolved with the support of available natural resource base and cultural trigger.

Famous temples include Lingaraj Temple, Muktesvara Temple, Rajarani Temple, Ananta Vasudeva Temple.

As a part of the Ekamra Festival, many cultural sub-festivals takes place in January in Bhubaneswar which includes Kalinga Mahotsav (for traditional martial arts), Dhauli-Kalinga Mahotsav (for classical dance forms), Rajarani Music Festival (for classical music) and Mukteswar Dance Festival (for Odishi dance).  Residents engage in khattis, or leisurely chats, that often take the form of freestyle intellectual conversation. <a href="https://incredibleindia.org/"target="_blank">Read More</a></p>

