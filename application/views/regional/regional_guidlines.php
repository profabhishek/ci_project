		<h3 style="text-align:center;">POLICY GUIDELINES ON SCHOLARSHIP ADMINISTERED BY INDIAN COUNCIL FOR CULTURAL RELATIONS </h3>
		<h4 style="text-align:center;">(FOR REGIONAL OFFICES)</h4>		
		<ul class="list-group">
			<li class="list-group-item ">No application will be accepted locally (within India) unless it is routed through the online application mechanism and within the stipulated period.</li>
			<li class="list-group-item ">ICCR does not award scholarship for MBBS/BDS courses.</li>
			<li class="list-group-item ">Expenditure on laboratory chemicals and other related incidental charges for students pursuing science and agriculture courses will have to be borne by the students themselves.  </li>
			<li class="list-group-item ">Applications for Casual Research/Diplomas/Short-term courses will not be entertained.</li>
			<li class="list-group-item ">Regional Offices to forward applications once they are received on the RO Portal to various Universities as per choice of applicant.</li>
			<li class="list-group-item ">RO confirms admission to Head Quarters with last date of joining University/Institute.</li>
			<li class="list-group-item ">Admission confirmed by a University in respect of a particular student is non-transferable and no efforts should be made to make any changes. </li>
			<li class="list-group-item ">ICCR, as a policy does not permit mid-term changes of Courses, College or University (with the exception of medical emergency).</li>
			<li class="list-group-item ">ICCR bears cost for medical treatment for minor ailments as per Central Government Health Scheme (CGHS) norms and in Government recognised hospitals.</li>
			<li class="list-group-item ">If a student is hospitalized in India for a period of one month or longer, the student’s living allowance will be reduced by 50%. </li>
			<li class="list-group-item ">If any of the ailments calling for long duration-treatment and long absence from college is diagnosed after seeking admission the student would be repatriated to his/her country for treatment. Prolonged absence from college results in losses to both the student (since he/she will not be permitted to appear in the examination due to lack of mandatory attendance) and the Council.</li>
			<li class="list-group-item ">Students admitted to various Colleges in India are mandatorily required to stay in hostel throughout the duration of their course if hostel accommodation is available/provided. Selected candidates will sign an Undertaking to this effect which will be sent to ICCR HQs by the Mission.</li>
			<li class="list-group-item ">ICCR will only pay hostel fee including electricity and not mess charges/security deposits/caution money. </li>
			<li class="list-group-item ">If hostel accommodation is not provided and private accommodation is hired, House Rent Allowance (HRA) will be released to the students only on submission of:
				<ul class="list-group">
				<li class="list-group-item ">Valid Rental Agreement between student and Landlord.</li>
				<li class="list-group-item ">Copy of Residential Permit (RP) with the same address as in rental agreement. </li>
				<li class="list-group-item ">Rent Receipt for amount paid to the Landlord. </li>
				</ul>
			</li>
			
			<li class="list-group-item ">A decision taken by the student to move out of hostel accommodation, without seeking prior permission would result in ICCR not paying for the rented accommodation. </li>
			<li class="list-group-item ">Students will not be permitted to change accommodation before expiry of existing Lease/Rental Agreement submitted to ICCR.</li>
			<li class="list-group-item ">As per rules of the Ministry of Home Affairs, Government of India, all students admitted to M.Phil/Ph.D/Post-Doctoral should be issued Research Visas and not Student Visas since it is not possible to convert Student Visa to Research Visa.</li>
			<li class="list-group-item ">As per Ministry of Home Affairs/Government of India guidelines, if a student arrives without a proper visa, even if his/her admission has been confirmed, he/she will be deported to his/her country for the required change in visas at no cost the Council and no guarantee of admission when he/she returns.</li>
			<li class="list-group-item ">Students intending to pursue M.Phil/Ph.D after completing 	their post-graduation even if they have provisional admission to M.Phil/Ph.D will have to return to their respective countries for the Research Visa Endorsement. Application for admission to M.Phil/Ph.D. has to be submitted online through the Mission.</li>
			<li class="list-group-item ">Regional Office will make necessary arrangements to receive scholars on arrival based on travel schedule provided by Mission/HQ.</li>
			<li class="list-group-item ">Regional Office will release three months advance stipend on pro-rata basis from date of arrival in India.</li>
			<li class="list-group-item ">Scholars should be advised to register online with FRRO to complete their Police registration in India within 2 weeks after arrival to avoid being penalised.</li>
			<li class="list-group-item ">Bonafide certificate will be issued to open bank account and register in the University. </li>
			<li class="list-group-item ">An orientation programme should be conducted by the RO for the scholars who have reported to them and they should be adequately briefed on living conditions, culture and social set-up in India and in particular the city they will be staying.</li>
			<li class="list-group-item ">If a student pays tuition fees/ other compulsory fees to the College/Institute, he/she is entitled to get reimbursement on submission of the original receipt/voucher etc. issued by the University/College/Institute. </li>
			<li class="list-group-item ">Monitor attendance and progress of scholar regularly. Attendance as per University norms will be followed by the students. No letter will be issued by RO for condonation of attendance on any ground.</li>
			<li class="list-group-item ">RO to monitor monthly payment schedule of stipend/HRA to scholars and simultaneously make entries in financial statement.</li>
			<li class="list-group-item ">Release TF/OCF on receipt of joining report as per approval of Competent Authority.</li>
			<li class="list-group-item ">Registration fee/tuition fee etc. would not be paid for the extension period unless approved by the Competent Authority. </li>
			<li class="list-group-item ">Participation in conference/seminar to present papers by PhD scholars is permitted only once in a calendar year and limited to participation in only a maximum of 2 conference during the full duration of the course The total registration fee admissible will not exceed Rs 5000/- per seminar/conference.Prior approval of ICCR Headquarters is required for participation in any Conference/Seminar and request must be submitted at least one month in advance</li>
			<li class="list-group-item ">Scholarship will be cancelled if 
				<ul class="list-group">
				<li class="list-group-item ">The student fails repeatedly or is involved in malpractices / anti-social / criminal activities, or is found violating the terms and conditions of ICCR scholarship schemes.</li>
				<li class="list-group-item ">The student gets involved in a law and order situation, violating law of land, the matter would be dealt with by the concerned law enforcing authorities in India.</li>
				<li class="list-group-item ">Council will not extend the scholarship period if student is detained/debarred from appearing in the exam due to shortage of attendance/malpractice </li>
				</ul>
			</li>
			<li class="list-group-item ">A student is entitled to receive scholarship up to a maximum of 3 weeks after declaration of result during which time he/she must complete all academic/ travel formalities. This date will be calculated on the basis of the online results declared.</li>
			<li class="list-group-item ">To drive in India, students must have a valid International Driving License.</li>
			<li class="list-group-item ">Students proceeding on a study tour within India should submit their study tour proposal certified by the Supervising Teacher or Head of the Institution concerned, stating that the tour is an integral part or essential to the course. </li>
			<li class="list-group-item ">Preference would be given to study tours conducted by the University or Institute concerned and a report should be submitted by the student on completion of the tour with the claim for reimbursement.</li>
			<li class="list-group-item ">Prior permission from the ICCR at least one month in advance should be taken by the student. <br/>
				The entitlements are:
 
				<ul class="list-group">
				<li class="list-group-item ">To-and-fro train fare (3 tier AC) or the actual bus fare.</li>
				<li class="list-group-item ">Daily allowance of Rs 200/per day for Metropolitan Cities and Rs.150/- per day for other cities. The daily allowance is payable in addition to the monthly living allowance, subject to the study tour not exceeding 30 days. All original tickets/vouchers are to be submitted for reimbursement after completion of tour.</li>
				</ul>
			</li>
			<li class="list-group-item ">Scholars who travel abroad during the academic year are not entitled to Stipend for the ex-India period. Any amount paid will be deducted on pro-rata basis.</li>
			
			
			
						
		</ul>
		<ul class="list-group">
		<li class="list-group-item">
				<b>Procedures on completion of course</b>
				<br/><br/> 
				
				<li class="list-group-item">Students should leave the country immediately after the completion of their studies. Under normal circumstances, the time gap between completion of studies and final departure should not exceed 3 weeks.</li>
				<li class="list-group-item">Marks memo should be submitted to ICCR before departure and letter for Exit Permit should be collected.</li>
				<li class="list-group-item">Those scholars eligible for return air ticket must submit a request in the proforma available in the Regional Offices and ICCR  headquarters at least 2 weeks prior to anticipated date of departure. In case the residential permit has expired the scholar will be solely responsible for the penalty levied at the time of departure at the airport.</li>
				<li class="list-group-item">Students who discontinue their studies and return to their home country will have to refund the expenditure incurred on them while in India to the Council.</li>
				
		</li>
		</ul>
