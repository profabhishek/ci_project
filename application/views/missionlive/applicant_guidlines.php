		<h3 style="text-align:center;">POLICY GUIDELINES ON SCHOLARSHIP ADMINISTERED BY INDIAN COUNCIL FOR CULTURAL RELATIONS </h3>
		<h4 style="text-align:center;">(FOR APPLICANTS)</h4>		
		<ul class="list-group">
			<li class="list-group-item ">No application will be accepted locally (within India) unless it is routed through the online application mechanism and within the stipulated period.<br/><br/>
				<ul class="list-group">
					<li class="list-group-item">In case of nominations by the local government/ dignitary, such cases may be duly examined by the Education Officer and forwarded with Ambassador’s approval within the stipulated period.</li>
					<li class="list-group-item">Applications should be complete in every detail. Certified copies of translations of documents which are not in English should be attached.</li>
					<li class="list-group-item">Students applying for M.Phil/Doctoral/Post-Doctoral courses should submit a synopsis along with the application.  </li>
					<li class="list-group-item">Students wishing to pursue performing arts should upload Video/Audio/YouTube link.</li>
				</ul>
			</li>
			<li class="list-group-item">
				<b>Confirmation of Admission:</b>
				<br/><br/> 
				<ul>
				<li class="list-group-item">Submission of application form does not guarantee confirmed admission.</li>
				<li class="list-group-item">Indian Universities/ Educational institutions are autonomous and independent bodies and have their own eligibility criteria on the basis of which they confirm admissions.</li>
				<li class="list-group-item">Admission confirmed by a University in respect of a particular student is non-transferable.</li>
				<li class="list-group-item"><b>Selection of Subjects, Courses and Universities</b><br/><br/> 
					<ul>
					
					<li class="list-group-item">An applicant should have studied maths, physics and chemistry at Higher Secondary level to be eligible for admission to science/engineering courses.</li>
					<li class="list-group-item">Applicants should clearly mention the course to which they are seeking admission while mentioning choices.</li>
					<li class="list-group-item">Applicants must refer to university websites or list of Universities where ICCR students are currently studying which is available at ICCR Website www.iccr.gov.in.</li>
					<li class="list-group-item">Applications for Casual Research/Diplomas/Short-term courses will not be entertained.</li>
					<li class="list-group-item">ICCR does not award scholarship for MBBS/BDS courses.</li>
					<li class="list-group-item">Expenditure on laboratory chemicals and other related incidental charges for students pursuing science and agriculture courses will have to be borne by the students themselves.</li>
					
					</ul>
				</li>
				</ul>
			</li>
			<li class="list-group-item "><b>English language proficiency</b><br/><br/> 
				<ul>
					<li class="list-group-item ">Since medium of instruction is English in all the Universities in India, applicants should have good knowledge of English to the extent that they are able to fluently speak in English and comprehend lessons in English without any difficulty.</li>					
				</ul>
			</li>
			<li class="list-group-item "><b>Change of Subject, College and University </b><br/><br/> 
				<ul>
					<li class="list-group-item ">ICCR, as a policy does not permit mid-term changes of Courses, College or University (with the exception of medical emergency).</li>		
					<li class="list-group-item ">Applicants are advised to go through the courses offered by the Universities carefully before finally submitting the application form.</li>	
				</ul>
			</li>
			<li class="list-group-item "><b>Medical Fitness </b><br/><br/> 
				<ul>
					<li class="list-group-item ">Applicant must produce a medical fitness certificate from the recognized hospital in the prescribed format available with the online application form. Care should be taken to ensure that you are not suffering from T.B., Cancer, AIDS, and ailments affecting vital organs or any female applicants is not in the family way.</li>		
					<li class="list-group-item ">ICCR bears cost for medical treatment for minor ailments as per Central Government Health Scheme (CGHS) norms and in government recognized hospitals.</li>	
					<li class="list-group-item ">If a student is hospitalized in India for a period of one month or longer, the student’s living allowance will be reduced by 50%. .</li>
					
				</ul><br/>
				<p>
				If any of the ailments calling for long duration-treatment and long absence from college is diagnosed after seeking admission the student would be repatriated to his/her country for treatment. Prolonged absence from college results in losses to both the student (since he/she will not be permitted to appear in the examination due to lack of mandatory attendance) and the Council.</p>
			</li>
				<li class="list-group-item "><b>Accommodation in India  </b><br/><br/> 
				<ul>
					<li class="list-group-item ">Students admitted to various Colleges in India are mandatorily required to stay in hostel throughout the duration of their course if hostel accommodation is available/provided. Selected candidates will sign an Undertaking to this effect which will be binding..</li>		
					<li class="list-group-item "> ICCR will only pay hostel fee including electricity and not mess charges/security deposits/caution money.</li>	
					<li class="list-group-item ">If hostel accommodation is not provided and private accommodation is hired, House Rent Allowance (HRA) will be released to the students only on submission of a) Valid Rental Agreement between student and Landlord b) copy of Residential Permit (RP) with the same address and c) Rent Receipt for amount paid to the Landlord.</li>
					<li class="list-group-item ">A decision taken by the student to move out of hostel accommodation, without seeking prior permission would result in ICCR not paying for the rented accommodation</li>
					<li class="list-group-item ">
						Students will not be permitted to change accommodation before expiry of existing Lease/Rental Agreement submitted to ICCR
					</li>
				</ul>				
			</li>
				<li class="list-group-item "><b>Issuing of visas and tickets   </b><br/><br/> 
				<ul>
					<li class="list-group-item ">As per Ministry of Home Affairs/Government of India guidelines, if a student arrives without a proper visa, even if his/her admission has been confirmed, he/she will be deported to his/her country for the required change in visas at no cost the Council and no guarantee of admission when he/she returns.</li>		
					<li class="list-group-item "> Students intending to pursue M.Phil/Ph.D after completing their post-graduation even if they have provisional 	admission to M.Phil/Ph.D will have to return to their  	respective countries for the Research Visa Endorsement.  	Application for admission to M.Phil/Ph.D. has to be submitted online through the Mission.</li>	
					
				</ul>				
			</li>
			<li class="list-group-item "><b>Payment of Tuition/Registration Fee  </b><br/><br/> 
				<ul>
					<li class="list-group-item ">If a student pays tuition fees/ other compulsory fees to the College/Institute, he/she is entitled to get reimbursement on submission of the original receipt/voucher etc. Issued by the University/College/Institute. .</li>		
					<li class="list-group-item "> Registration fee/tuition fee etc. would not be paid for the extension period unless approved by the Competent Authority.</li>	
					<li class="list-group-item "> Participation in conference / seminar to present papers by PhD scholars is permitted only once in a calendar year and limited to participation in only a maximum of 2 conference during the full duration of the course The total registration fee admissible will not exceed Rs 5000/- per seminar/conference . Prior approval of ICCR Headquarters is required for participation in any Conference / Seminar and request must be submitted at least one month in advance.</li>
					
				</ul>				
			</li>
			<li class="list-group-item "><b>Extension/Revival/Discontinuation of Scholarship  </b><br/><br/> 
				<ul>
					<li class="list-group-item ">Scholarship will be cancelled if the student fails repeatedly or is involved in malpractices / anti-social / criminal activities, or is found violating the terms and conditions of ICCR scholarship schemes.</li>		
					<li class="list-group-item "> In case a student gets involved in a law and order situation, violating law of land, the matter would be dealt with by the concerned law enforcing authorities in India. .</li>	
					<li class="list-group-item "> Due care should be taken by the students while filling up of Joining Report after arrival in India and joining the University.</li>
					<li class="list-group-item ">A student is entitled to receive scholarship up to a maximum of 3 weeks after declaration of result. This date will be calculated on the basis of the online results declared. </li>
					
				</ul>				
			</li>
			<li class="list-group-item "><b>Miscellaneous </b><br/><br/> 
				<ul>
					<li class="list-group-item ">Applicants should carry at least Rs.50,000/- with them to meet incidental expenditure on arrival.</li>		
					<li class="list-group-item "> Students should ensure that they complete their Police registration in India within 2 weeks after arrival to avoid being penalised.</li>	
					<li class="list-group-item "> The students who are awarded scholarships should bring with them all original documents relating to their qualifications in original for verification by the respective college/university at the time of admission.</li>
					<li class="list-group-item ">Certified copies of all documents should be accompanied with English translations and syllabus of the last qualifying examination </li>
					<li class="list-group-item ">To drive in India, students must have a valid International Driving License.</li>
					
				</ul>				
			</li>
